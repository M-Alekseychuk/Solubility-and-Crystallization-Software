/**
 * Normalizes solvent string for resilient matching (ignoring hyphens, spaces, cases, numbers, brackets)
 */
export function normalizeSolventKey(name: string): string {
  return (name || '')
    .toLowerCase()
    .replace(/[\s\-_(),/[\]]/g, '');
}

/**
 * Finds reference solvent details by fuzzy/alias matching
 */
export function findSolventInDatabase(queryName: string): ReferenceSolvent | undefined {
  if (!queryName) return undefined;
  const clean = queryName.trim().toLowerCase();
  const normalized = normalizeSolventKey(queryName);

  // 1. Exact name match (case-insensitive)
  const exact = masterSolventDatabase.find(s => s.name.toLowerCase() === clean);
  if (exact) return exact;

  // 2. Normalized name match
  const normMatch = masterSolventDatabase.find(s => normalizeSolventKey(s.name) === normalized);
  if (normMatch) return normMatch;

  // 3. Aliases match
  const aliasMatch = masterSolventDatabase.find(s => {
    if (!s.aliases) return false;
    return s.aliases.some(a => a.toLowerCase() === clean || normalizeSolventKey(a) === normalized);
  });
  if (aliasMatch) return aliasMatch;

  // 4. Substring / partial match
  const partial = masterSolventDatabase.find(s => {
    const sNorm = normalizeSolventKey(s.name);
    return normalized.length >= 4 && (sNorm.includes(normalized) || normalized.includes(sNorm));
  });
  if (partial) return partial;

  return undefined;
}

/**
 * Enriches a user-provided solvent with missing parameters or updates outdated Hansen parameters from the master database.
 * Preserves custom cost entries and user overrides, but synchronizes authoritative HSP and EHS scores.
 */
export function enrichSolventWithReference(userSolvent: Solvent): { solvent: Solvent; changed: boolean; updatedFields: string[] } {
  const ref = findSolventInDatabase(userSolvent.name);
  if (!ref) {
    return { solvent: { ...userSolvent }, changed: false, updatedFields: [] };
  }

  const updated: Solvent = { ...userSolvent };
  const updatedFields: string[] = [];

  const isEmpty = (v: any) => v === '' || v === undefined || v === null || Number.isNaN(v);

  // Synchronize authoritative Hansen parameters if missing or different
  if (ref.hansenD !== undefined && updated.hansenD !== ref.hansenD) {
    updated.hansenD = ref.hansenD;
    updatedFields.push('Hansen dD');
  }
  if (ref.hansenP !== undefined && updated.hansenP !== ref.hansenP) {
    updated.hansenP = ref.hansenP;
    updatedFields.push('Hansen dP');
  }
  if (ref.hansenH !== undefined && updated.hansenH !== ref.hansenH) {
    updated.hansenH = ref.hansenH;
    updatedFields.push('Hansen dH');
  }

  // Synchronize physical & hazard data if missing
  if (isEmpty(updated.casNumber) && ref.casNumber) {
    updated.casNumber = ref.casNumber;
    updatedFields.push('CAS Number');
  }
  if (isEmpty(updated.viscosity) && ref.viscosity !== undefined) {
    updated.viscosity = ref.viscosity;
    updatedFields.push('Viscosity');
  }
  if (isEmpty(updated.surfaceTension) && ref.surfaceTension !== undefined) {
    updated.surfaceTension = ref.surfaceTension;
    updatedFields.push('Surface Tension');
  }
  if (isEmpty(updated.ghsStatements) && ref.ghsStatements) {
    updated.ghsStatements = ref.ghsStatements;
    updatedFields.push('GHS Labels');
  }

  if (isEmpty(updated.boilingPoint) && !isEmpty(ref.boilingPoint)) {
    updated.boilingPoint = ref.boilingPoint;
    updatedFields.push('Boiling Point');
  }

  if (isEmpty(updated.meltingPoint) && !isEmpty(ref.meltingPoint)) {
    updated.meltingPoint = ref.meltingPoint;
    updatedFields.push('Melting Point');
  }

  if (isEmpty(updated.dielectricConstant) && !isEmpty(ref.dielectricConstant)) {
    updated.dielectricConstant = ref.dielectricConstant;
    updatedFields.push('Dielectric Constant');
  }

  if (isEmpty(updated.flashPoint) && !isEmpty(ref.flashPoint)) {
    updated.flashPoint = ref.flashPoint;
    updatedFields.push('Flash Point');
  }

  if (updated.ichClass !== ref.ichClass) {
    updated.ichClass = ref.ichClass;
    updatedFields.push('ICH Class');
  }

  if (!isEmpty(ref.ehsScore) && updated.ehsScore !== ref.ehsScore) {
    updated.ehsScore = ref.ehsScore;
    updatedFields.push('EHS Score');
  }

  if (isEmpty(updated.polarityIndex) && !isEmpty(ref.polarityIndex)) {
    updated.polarityIndex = ref.polarityIndex;
    updatedFields.push('Polarity Index');
  }

  if (isEmpty(updated.polarityProfile) && !isEmpty(ref.polarityProfile)) {
    updated.polarityProfile = ref.polarityProfile;
    updatedFields.push('Polarity');
  }

  if (isEmpty(updated.waterMiscibility) && !isEmpty(ref.waterMiscibility)) {
    updated.waterMiscibility = ref.waterMiscibility;
    updatedFields.push('Water Miscibility');
  }

  if (isEmpty(updated.miscibilityPercentage) && !isEmpty(ref.miscibilityPercentage)) {
    updated.miscibilityPercentage = ref.miscibilityPercentage;
    updatedFields.push('Miscibility %');
  }

  return {
    solvent: updated,
    changed: updatedFields.length > 0,
    updatedFields
  };
}

/**
 * Enriches an entire array of solvents, preserving order and IDs.
 */
export function enrichSolventsList(solvents: Solvent[]): { enriched: Solvent[]; updatedCount: number; totalFieldsUpdated: number } {
  let updatedCount = 0;
  let totalFieldsUpdated = 0;

  const enriched = solvents.map(s => {
    const res = enrichSolventWithReference(s);
    if (res.changed) {
      updatedCount++;
      totalFieldsUpdated += res.updatedFields.length;
    }
    return res.solvent;
  });

  return { enriched, updatedCount, totalFieldsUpdated };
}

export function getSolventNames(): string[] {
  try {
    const saved = localStorage.getItem('hplc-solvents') || localStorage.getItem('hplc-solvents-standard');
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed.map((s: Solvent) => s.name).filter(Boolean);
      }
    }
  } catch (e) {
    // fallback
  }
  return defaultSolvents.map(s => s.name);
}
